#!/bin/sh
set -e

#--------------------------------------------------------------------------------------------------
# Settings
#--------------------------------------------------------------------------------------------------

source="https://github.com/omega-gg"

#--------------------------------------------------------------------------------------------------
# Syntax
#--------------------------------------------------------------------------------------------------

if [ $# != 1 -a $# != 2 ] \
   || \
   [ $1 != "win64" -a $1 != "macOS" -a $1 != "linux" ] \
   || \
   [ $# = 2 -a "$2" != "mingw" -a "$2" != "msvc" ]; then

    echo "Usage: 3rdparty <win64 | macOS | linux> [mingw | msvc]"
    echo ""
    echo "Downloads Qt and the Windows compilers in ../3rdparty/<platform>, like Sky does."

    exit 1
fi

compiler="${2:-mingw}"

#--------------------------------------------------------------------------------------------------
# Clone
#--------------------------------------------------------------------------------------------------

cd "$(dirname "$0")/.."

if [ ! -d "3rdparty" ]; then

    git clone $source/3rdparty
fi

#--------------------------------------------------------------------------------------------------
# 3rdparty
#--------------------------------------------------------------------------------------------------

cd 3rdparty

sh environment.sh $compiler
sh environment.sh qt6

sh generate.sh $1
